            <p>
                Многие мальчишки мечтают стать военными моряками, и первым шагом в осуществлении их мечты может стать
                учеба в Нахимовском училище.
            </p>
            <p>
                За годы существования нахимовских училищ не одно поколение юношей прошло школу флотской дружбы и
                настоящего братства. Все они воспитаны в духе верности воинскому долгу, отечеству, славным боевым
                традициям Российского военно-морского флота. Как бы ни сложилась в дальнейшем жизнь
                выпускников-нахимовцев, они остаются до конца своих дней верными флотскому, нахимовскому братству.
            </p>
            <p>
                Сегодня легендарное Нахимовское училище в Санкт-Петербурге имеет четыре действующих филиала: во
                Владивостоке, Мурманске, Калининграде и Севастополе. В 2024 году планируется открыть филиал в Мариуполе.
                Нахимовские и суворовские училища были созданы в соответствии с постановлением СНК СССР и ЦК ВКПБ от 21
                августа 1943 года. Наименование «Нахимовские» они получили в честь великого русского флотоводца адмирала
                Павла Степановича Нахимова, героя Крымской войны 1853–1856 гг.
            </p>
            <p>
                В училищах была создана такая обстановка для занятий, которая позволяла, изучая теорию, развивать у
                нахимовцев морские качества, прививать любовь к романтике флотской службы, давать глубокие и
                всесторонние общеобразовательные знания. Большое внимание уделялось строевой подготовке, которая
                способствовала высокой слаженности и воинской выправке, воспитывала чувство флотского товарищества,
                коллективизма, другие качества и навыки, необходимые будущим офицерам. Особую роль отводилось учебной
                практике, включавшей в себя военно-морскую, общевойсковую и физическую подготовку.
            </p>
            <p>
                Сегодня Нахимовское военно-морское училище продолжает традиции, заложенные в первые годы работы, и
